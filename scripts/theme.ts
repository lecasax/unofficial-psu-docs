// Generates src/theme.css, the Material 3 color theme, from one seed color.
// Usage: npm run theme -- "#4cc3ff"
import { writeFileSync } from 'node:fs';
import { argbFromHex, DynamicScheme, Hct, Variant } from '@ktibow/material-color-utilities-nightly';
import { colors, genCSS } from 'm3-svelte/etc/colors';

const seed = process.argv[2] ?? '#4cc3ff';
const sourceColorHcts = [Hct.fromInt(argbFromHex(seed))];
const scheme = (isDark: boolean) =>
	new DynamicScheme({
		sourceColorHcts,
		variant: Variant.TONAL_SPOT,
		contrastLevel: 0,
		specVersion: '2025',
		isDark
	});

// Same color set as the m3-svelte theme page with its default options.
const used = colors.filter((c) => !/dim|bright|fixed/.test(c.name));

const css = `/* Generated by scripts/theme.ts from seed ${seed}. Do not edit by hand. */
@function --m3-density(--size) {
  result: var(--size);
}
${genCSS(scheme(false), scheme(true), used)}
`;

writeFileSync(new URL('../src/theme.css', import.meta.url), css);
console.log(`src/theme.css written from ${seed}`);
